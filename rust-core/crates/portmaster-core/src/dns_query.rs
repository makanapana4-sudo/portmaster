use crate::dns_wire::{
    DnsWireError, DNS_HEADER_SIZE, DNS_TYPE_OPT, MAX_DNS_LABEL_LENGTH,
};

/// Options for constructing a standard DNS query.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DnsQueryOptions {
    pub recursion_desired: bool,
    pub udp_payload_size: Option<u16>,
    pub dnssec_ok: bool,
}

impl Default for DnsQueryOptions {
    fn default() -> Self {
        Self {
            recursion_desired: true,
            udp_payload_size: Some(1232),
            dnssec_ok: false,
        }
    }
}

/// Builds a single-question IN-class DNS query.
///
/// Transaction IDs should be generated by a cryptographically secure source
/// in the caller. Non-ASCII input must be converted to IDNA ASCII before
/// calling this function.
pub fn build_dns_query(
    name: &str,
    record_type: u16,
    transaction_id: u16,
    options: DnsQueryOptions,
) -> Result<Vec<u8>, DnsWireError> {
    if options.dnssec_ok && options.udp_payload_size.is_none() {
        return Err(DnsWireError::DnssecOkRequiresEdns);
    }

    if let Some(payload_size) = options.udp_payload_size {
        if payload_size < 512 {
            return Err(DnsWireError::InvalidUdpPayloadSize);
        }
    }

    let mut output = Vec::with_capacity(64);
    output.resize(DNS_HEADER_SIZE, 0);

    output[0..2].copy_from_slice(&transaction_id.to_be_bytes());
    let flags = if options.recursion_desired { 0x0100_u16 } else { 0 };
    output[2..4].copy_from_slice(&flags.to_be_bytes());
    output[4..6].copy_from_slice(&1_u16.to_be_bytes());
    output[10..12].copy_from_slice(
        &u16::from(options.udp_payload_size.is_some()).to_be_bytes(),
    );

    encode_name(name, &mut output)?;
    output.extend_from_slice(&record_type.to_be_bytes());
    output.extend_from_slice(&1_u16.to_be_bytes());

    if let Some(payload_size) = options.udp_payload_size {
        output.push(0);
        output.extend_from_slice(&DNS_TYPE_OPT.to_be_bytes());
        output.extend_from_slice(&payload_size.to_be_bytes());

        let edns_flags = if options.dnssec_ok { 0x8000_u32 } else { 0 };
        output.extend_from_slice(&edns_flags.to_be_bytes());
        output.extend_from_slice(&0_u16.to_be_bytes());
    }

    Ok(output)
}

fn encode_name(name: &str, output: &mut Vec<u8>) -> Result<(), DnsWireError> {
    if name == "." {
        output.push(0);
        return Ok(());
    }

    let name = name.strip_suffix('.').unwrap_or(name);
    if name.is_empty() || !name.is_ascii() {
        return Err(DnsWireError::InvalidDomainName);
    }

    let mut wire_length = 1usize;
    for label in name.split('.') {
        if label.is_empty() {
            return Err(DnsWireError::InvalidDomainName);
        }
        if label.len() > MAX_DNS_LABEL_LENGTH {
            return Err(DnsWireError::LabelTooLong);
        }
        if label.bytes().any(|byte| !matches!(byte, 0x21..=0x7e) || byte == b'\\') {
            return Err(DnsWireError::InvalidDomainName);
        }

        wire_length = wire_length
            .checked_add(label.len() + 1)
            .ok_or(DnsWireError::LengthOverflow)?;
        if wire_length > 255 {
            return Err(DnsWireError::NameTooLong);
        }

        output.push(label.len() as u8);
        output.extend(label.bytes().map(|byte| byte.to_ascii_lowercase()));
    }

    output.push(0);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dns_wire::{parse_dns_message, DNS_HEADER_SIZE};

    #[test]
    fn builds_recursive_a_query_with_edns() {
        let options = DnsQueryOptions::default();
        let packet = build_dns_query("ExAmPlE.com.", 1, 0x1234, options).unwrap();
        let metadata = parse_dns_message(&packet).unwrap();

        assert_eq!(metadata.id, 0x1234);
        assert!(!metadata.is_response());
        assert_eq!(metadata.flags & 0x0100, 0x0100);
        assert_eq!(metadata.question_count, 1);
        assert_eq!(metadata.additional_count, 1);
        assert_eq!(
            metadata.first_question.unwrap().name,
            "example.com."
        );
        assert_eq!(metadata.minimum_record_ttl_secs, None);
    }

    #[test]
    fn builds_dnssec_ok_flag_in_edns_record() {
        let packet = build_dns_query(
            "example.org",
            28,
            7,
            DnsQueryOptions {
                recursion_desired: false,
                udp_payload_size: Some(1232),
                dnssec_ok: true,
            },
        )
        .unwrap();

        let metadata = parse_dns_message(&packet).unwrap();
        assert_eq!(metadata.flags & 0x0100, 0);
        assert_eq!(metadata.additional_count, 1);
        assert_eq!(&packet[packet.len() - 6..packet.len() - 2], &[0, 0, 0x80, 0]);
    }

    #[test]
    fn builds_root_query_without_edns() {
        let packet = build_dns_query(
            ".",
            28,
            9,
            DnsQueryOptions {
                recursion_desired: true,
                udp_payload_size: None,
                dnssec_ok: false,
            },
        )
        .unwrap();

        assert_eq!(packet.len(), DNS_HEADER_SIZE + 1 + 4);
        let metadata = parse_dns_message(&packet).unwrap();
        assert_eq!(
            metadata.first_question.unwrap().name,
            "."
        );
        assert_eq!(metadata.additional_count, 0);
    }

    #[test]
    fn rejects_invalid_names_and_edns_options() {
        assert_eq!(
            build_dns_query("", 1, 1, DnsQueryOptions::default()).err(),
            Some(DnsWireError::InvalidDomainName)
        );
        assert_eq!(
            build_dns_query("example..com", 1, 1, DnsQueryOptions::default()).err(),
            Some(DnsWireError::InvalidDomainName)
        );
        assert_eq!(
            build_dns_query(
                &"a".repeat(64),
                1,
                1,
                DnsQueryOptions::default()
            )
            .err(),
            Some(DnsWireError::LabelTooLong)
        );
        assert_eq!(
            build_dns_query(
                "example.com",
                1,
                1,
                DnsQueryOptions {
                    recursion_desired: true,
                    udp_payload_size: Some(256),
                    dnssec_ok: false,
                }
            )
            .err(),
            Some(DnsWireError::InvalidUdpPayloadSize)
        );
        assert_eq!(
            build_dns_query(
                "example.com",
                1,
                1,
                DnsQueryOptions {
                    recursion_desired: true,
                    udp_payload_size: None,
                    dnssec_ok: true,
                }
            )
            .err(),
            Some(DnsWireError::DnssecOkRequiresEdns)
        );
    }
}
